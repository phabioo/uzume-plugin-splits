local t = require("t")
local model = require("model")
local H = require("harness")

local function run(list, times)
  local att = model.new_attempt()
  for _, ms in ipairs(times) do
    if ms == "skip" then model.record_skip(list, att) else model.record_split(list, att, ms) end
  end
  return att
end

t.case("first finished run becomes the personal best and sets the golds", function()
  local list = H.list({ "A", "B", "C" })
  local att = run(list, { 1000, 2500, 4000 })
  t.ok(model.is_done(list, att))
  local info = model.commit(list, att, true)
  local set = model.set(list)
  t.ok(info.pb)
  t.eq(info.total, 4000)
  t.eq(set.pb.total, 4000)
  t.eq(set.pb.times[list.splits[2].id], 2500)
  t.eq(set.golds[list.splits[1].id], 1000)
  t.eq(set.golds[list.splits[2].id], 1500)
  t.eq(set.golds[list.splits[3].id], 1500)
  t.eq(list.completed, 1)
  t.eq(model.sum_of_best(list), 4000)
end)

t.case("a slower run keeps the PB but a better segment becomes gold", function()
  local list = H.list({ "A", "B" })
  model.commit(list, run(list, { 1000, 3000 }), true)
  local att = run(list, { 1200, 3100 }) -- B segment 1900 beats 2000
  local info = model.commit(list, att, true)
  local set = model.set(list)
  t.ok(not info.pb)
  t.eq(set.pb.total, 3000)
  t.eq(set.golds[list.splits[1].id], 1000)
  t.eq(set.golds[list.splits[2].id], 1900)
  t.eq(list.completed, 2)
  t.eq(model.sum_of_best(list), 2900)
end)

t.case("a faster run replaces the PB", function()
  local list = H.list({ "A", "B" })
  model.commit(list, run(list, { 1000, 3000 }), true)
  local info = model.commit(list, run(list, { 900, 2800 }), true)
  t.ok(info.pb)
  t.eq(info.old_total, 3000)
  t.eq(model.set(list).pb.total, 2800)
end)

t.case("equal time is not a new PB", function()
  local list = H.list({ "A", "B" })
  model.commit(list, run(list, { 1000, 3000 }), true)
  t.ok(not model.commit(list, run(list, { 1000, 3000 }), true).pb)
end)

t.case("skipping: no time for the skipped split, no gold for the merged segment", function()
  local list = H.list({ "A", "B", "C" })
  local att = run(list, { 1000, "skip", 4000 })
  local segs = model.segments(list, att)
  t.eq(segs[1], 1000)
  t.eq(segs[2], nil)
  t.eq(segs[3], nil)
  model.commit(list, att, true)
  local set = model.set(list)
  t.eq(set.pb.times[list.splits[2].id], nil)
  t.eq(set.pb.times[list.splits[3].id], 4000)
  t.eq(set.golds[list.splits[1].id], 1000)
  t.eq(set.golds[list.splits[3].id], nil)
  t.eq(model.sum_of_best(list), nil, "not every split has a best segment")
end)

t.case("the last split cannot be skipped; undo removes results", function()
  local list = H.list({ "A", "B" })
  local att = model.new_attempt()
  t.ok(model.record_skip(list, att))
  t.ok(not model.record_skip(list, att), "B is the last split")
  t.ok(model.undo(att))
  t.ok(model.undo(model.new_attempt()) == false)
  t.eq(model.current_index(att), 1)
end)

t.case("unfinished attempt: only golds are committed", function()
  local list = H.list({ "A", "B", "C" })
  local att = run(list, { 800, 1900 })
  local info = model.commit(list, att, false)
  local set = model.set(list)
  t.ok(not info.pb)
  t.eq(set.pb, nil)
  t.eq(set.golds[list.splits[1].id], 800)
  t.eq(set.golds[list.splits[2].id], 1100)
  t.eq(list.completed, 0)
end)

t.case("is_gold compares with the stored best segment", function()
  local list = H.list({ "A", "B" })
  model.commit(list, run(list, { 1000, 3000 }), true)
  local att = run(list, { 900 })
  t.ok(model.is_gold(list, att, 1))
  att = run(list, { 1100 })
  t.ok(not model.is_gold(list, att, 1))
end)

t.case("game time and real time keep separate bests", function()
  local list = H.list({ "A" })
  model.commit(list, run(list, { 1000 }), true)
  list.timing = "real"
  t.eq(model.set(list).pb, nil)
  model.commit(list, run(list, { 5000 }), true)
  t.eq(model.set(list).pb.total, 5000)
  list.timing = "game"
  t.eq(model.set(list).pb.total, 1000)
end)

t.case("editing: add, rename, move, delete cleans up times", function()
  local list = H.list({ "A", "B", "C" })
  local b = list.splits[2].id
  model.commit(list, run(list, { 1000, 2000, 3000 }), true)
  t.ok(model.rename(list, b, "  Bee | x "))
  t.eq(list.splits[2].name, "Bee / x")
  t.ok(model.move(list, b, -1))
  t.eq(list.splits[1].id, b)
  t.ok(not model.move(list, b, -1))
  t.ok(model.delete(list, b))
  t.eq(#list.splits, 2)
  t.eq(model.set(list).pb.times[b], nil)
  t.eq(model.set(list).golds[b], nil)
  local id = model.add(list, "D")
  t.ok(id and id ~= b, "ids are not reused")
  t.eq(select(2, model.add(list, "   ")), "name")
end)

t.case("at most MAX_SPLITS", function()
  local list = model.new_list()
  for i = 1, model.MAX_SPLITS do t.ok(model.add(list, "S" .. i)) end
  local id, why = model.add(list, "one more")
  t.eq(id, nil)
  t.eq(why, "full")
end)

t.case("rule normalization", function()
  local ok, r = model.normalize_rule({ kind = "memory", addr = 0x2000, size = "u16", cmp = "==", value = 7, junk = 1 })
  t.ok(ok)
  t.eq(r, { kind = "memory", addr = 0x2000, size = "u16", cmp = "=", value = 7 })
  ok, r = model.normalize_rule({ kind = "memory", addr = 5, size = "u8", cmp = "changed", value = 99 })
  t.eq(r, { kind = "memory", addr = 5, size = "u8", cmp = "changed" })
  t.eq(select(2, model.normalize_rule({ kind = "memory", addr = 5, size = "u8", cmp = "=", value = 256 })), "value")
  t.eq(select(2, model.normalize_rule({ kind = "memory", addr = -1, size = "u8", cmp = "=", value = 1 })), "addr")
  t.eq(select(2, model.normalize_rule({ kind = "memory", addr = 1, size = "u64", cmp = "=", value = 1 })), "size")
  t.eq(select(2, model.normalize_rule({ kind = "memory", addr = 1, size = "u8", cmp = "~", value = 1 })), "cmp")
  t.eq(select(2, model.normalize_rule({ kind = "badge", n = 9 })), "badge")
  t.eq(select(2, model.normalize_rule({ kind = "location", zone = 1.5 })), "zone")
  t.eq(select(2, model.normalize_rule("x")), "kind")
  ok, r = model.normalize_rule(nil)
  t.ok(ok and r == nil)
end)

t.case("sanitize drops garbage and keeps valid data", function()
  t.eq(model.sanitize(nil), nil)
  t.eq(model.sanitize({ v = 2, splits = {} }), nil)
  local list = H.list({ "A", "B" })
  model.commit(list, run(list, { 1000, 2000 }), true)
  local copy = model.sanitize(require("util").copy(list))
  t.eq(copy.splits, list.splits)
  t.eq(copy.sets, list.sets)
  local bad = model.sanitize({ v = 1, timing = "weird", fps = "x", splits = {
    { id = "s1", name = "ok", rule = { kind = "zzz" } }, { id = "s1", name = "dup" }, { id = 5, name = "n" }, { id = "s2", name = "  " } },
    sets = { game = { pb = { total = -4, times = {} }, golds = { s1 = "x" } } } })
  t.eq(bad.timing, "game")
  t.eq(bad.fps, 60)
  t.eq(#bad.splits, 1)
  t.eq(bad.splits[1].rule, nil)
  t.eq(bad.sets.game.pb, nil)
  t.eq(bad.sets.game.golds, {})
  t.ok(bad.next_id >= 2)
end)

t.case("sum of best: all, missing and empty; comparison choice and old data", function()
  local list = H.list({ "A", "B", "C" })
  t.eq(model.sum_of_best(H.list({})), nil)
  t.eq(list.compare, "pb")
  local g = model.set(list).golds
  g[list.splits[1].id], g[list.splits[3].id] = 900, 700
  t.eq(model.sum_of_best(list), nil, "B has no best segment")
  local cum = model.best_cumulative(list)
  t.eq(cum[list.splits[1].id], 900)
  t.eq(cum[list.splits[2].id], nil, "the cumulative best ends at the first gap")
  t.eq(cum[list.splits[3].id], nil)
  g[list.splits[2].id] = 500
  t.eq(model.sum_of_best(list), 2100)
  t.eq(model.best_cumulative(list)[list.splits[3].id], 2100)
  -- comparison: pb by default, best segments on request
  model.set(list).pb = { total = 3000, times = { [list.splits[1].id] = 1000, [list.splits[3].id] = 3000 } }
  t.eq(model.comparison(list)[list.splits[1].id], 1000)
  t.eq(model.comparison_total(list), 3000)
  list.compare = "best"
  t.eq(model.comparison(list)[list.splits[2].id], 1400)
  t.eq(model.comparison_total(list), 2100)
  -- stored lists without the new fields get the defaults; bad values fall back
  local old = model.sanitize({ v = 1, splits = { { id = "s1", name = "A" } } })
  t.eq(old.compare, "pb")
  t.eq(old.start_rule, nil)
  t.eq(old.reset_rule, nil)
  t.eq(model.sanitize({ v = 1, compare = "x", start_rule = { kind = "bogus" }, splits = {} }).compare, "pb")
  local ok = model.sanitize({ v = 1, compare = "best", splits = {},
    start_rule = { kind = "badge", n = 2 }, reset_rule = { kind = "location", zone = 5 } })
  t.eq(ok.compare, "best")
  t.eq(ok.start_rule, { kind = "badge", n = 2 })
  t.eq(ok.reset_rule, { kind = "location", zone = 5 })
  t.ok(not model.set_list_rule(list, "start_rule", { kind = "bogus" }))
  t.ok(not model.set_list_rule(list, "other", nil))
end)
