local t = require("t")
local fb_mock = require("fb_mock")
local rules = require("rules")
local textio = require("textio")

local function setup(rule_text, initial)
  local mock = fb_mock.new({ memory = { { addr = 0x2000, data = string.pack("<I4", initial or 0) } } })
  local ok, rule = textio.parse_rule(rule_text)
  assert(ok, "rule text")
  return mock, rules.arm(mock.fb, rule)
end

t.case("compare operators", function()
  t.ok(rules.compare("=", 3, 3) and not rules.compare("=", 3, 4))
  t.ok(rules.compare("!=", 3, 4) and not rules.compare("!=", 3, 3))
  t.ok(rules.compare(">", 4, 3) and not rules.compare(">", 3, 3))
  t.ok(rules.compare(">=", 3, 3) and not rules.compare(">=", 2, 3))
  t.ok(rules.compare("<", 2, 3) and not rules.compare("<", 3, 3))
  t.ok(rules.compare("<=", 3, 3) and not rules.compare("<=", 4, 3))
end)

t.case("arming a memory rule watches exactly its range", function()
  local mock = setup("mem 0x2000 u16 = 5")
  t.eq(mock.watches.rule, { addr = 0x2000, len = 2 })
  rules.disarm(mock.fb)
  t.eq(mock.watches.rule, nil)
  local m2, st = setup("badge 2")
  t.eq(m2.watches.rule, nil)
  t.eq(st.rule.kind, "badge")
  t.eq(rules.arm(m2.fb, nil), nil)
end)

t.case("fires on the change from false to true", function()
  local mock, st = setup("mem 0x2000 u8 >= 3", 0)
  t.ok(not rules.step_memory(mock.fb, st)) -- baseline: false
  mock.poke(0x2000, 1, 2)
  t.ok(not rules.step_memory(mock.fb, st))
  mock.poke(0x2000, 1, 3)
  t.ok(rules.step_memory(mock.fb, st))
  t.ok(not rules.step_memory(mock.fb, st), "only once while it stays true")
end)

t.case("a condition already true at the start waits for a new edge", function()
  local mock, st = setup("mem 0x2000 u8 = 5", 5)
  t.ok(not rules.step_memory(mock.fb, st))
  t.ok(not rules.step_memory(mock.fb, st))
  mock.poke(0x2000, 1, 0)
  t.ok(not rules.step_memory(mock.fb, st))
  mock.poke(0x2000, 1, 5)
  t.ok(rules.step_memory(mock.fb, st))
end)

t.case("changed fires on every different value", function()
  local mock, st = setup("mem 0x2000 u32 changed", 10)
  t.ok(not rules.step_memory(mock.fb, st))
  t.ok(not rules.step_memory(mock.fb, st))
  mock.poke(0x2000, 4, 11)
  t.ok(rules.step_memory(mock.fb, st))
  t.ok(not rules.step_memory(mock.fb, st))
end)

t.case("unreadable memory never fires and keeps the baseline", function()
  local mock, st = setup("mem 0x9000 u8 = 1")
  t.ok(not rules.step_memory(mock.fb, st))
  mock.poke(0x9000, 1, 0)
  t.ok(not rules.step_memory(mock.fb, st))
  mock.poke(0x9000, 1, 1)
  t.ok(rules.step_memory(mock.fb, st))
end)

t.case("every size and operator is read with the right width", function()
  local mock = fb_mock.new({ memory = { { addr = 0x100, data = string.pack("<I4", 0x11223344) } } })
  t.eq(mock.fb.memory.u8(0x100), 0x44)
  t.eq(mock.fb.memory.u16(0x100), 0x3344)
  t.eq(mock.fb.memory.u32(0x100), 0x11223344)
  local _, st = textio.parse_rule("mem 0x100 u16 != 7")
  t.eq(rules.summary(st), "0x100 u16 != 7")
  t.eq(rules.summary(nil), nil)
end)
