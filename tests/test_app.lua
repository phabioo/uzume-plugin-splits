t.case("undo after the finish restores the previous personal best", function()
  local mock, app = H.boot({ names = { "A", "B" } })
  local function run(ticks_a, ticks_b)
    mock.hotkey("split"); mock.tick(ticks_a, 2); mock.hotkey("split"); mock.tick(ticks_b, 2); mock.hotkey("split")
  end
  run(30, 30)
  t.eq(stored(mock).sets.game.pb.total, 2000)
  mock.hotkey("reset")
  run(15, 15) -- 1000 ms: new PB
  t.eq(stored(mock).sets.game.pb.total, 1000)
  t.eq(stored(mock).completed, 2)
  mock.hotkey("undo")
  t.eq(state(app), "running")
  t.eq(stored(mock).sets.game.pb.total, 2000)
  t.eq(stored(mock).completed, 1)
  mock.tick(15, 2)
  mock.hotkey("split") -- finishes again after the undo: 500 + 1000 = 1500 ms, still a PB
  t.eq(stored(mock).sets.game.pb.total, 1500)
end)

