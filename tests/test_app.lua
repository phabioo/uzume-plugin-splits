local function state(app) return app.timer.state end
local function stored(mock) return mock.store.data[H.KEY] end

t.case("hotkeys: start, split, finish; timer math on frames", function()
  local mock, app = H.boot({ names = { "A", "B" } })
  t.eq(state(app), "idle")
  mock.hotkey("split") -- start
  t.eq(state(app), "running")
  t.eq(app.list.attempts, 1)
  mock.tick(30, 2) -- 60 frames at 60 fps
  t.eq(H.text(mock, "hud", "time"), "0:01.00")
  mock.hotkey("split")
  t.eq(app.att.results[1].time, 1000)
  t.eq(H.text(mock, "hud", "split"), "B")
  mock.tick(15, 2)
  mock.hotkey("split") -- last split
  t.eq(state(app), "finished")
  t.eq(app.att.results[2].time, 1500)
  t.eq(stored(mock).sets.game.pb.total, 1500)
  t.eq(stored(mock).completed, 1)
  t.eq(H.text(mock, "hud", "split"), "New personal best")
  mock.tick(10, 2)
  t.eq(H.text(mock, "hud", "time"), "0:01.50", "finished timer stays")
  mock.hotkey("split")
  t.eq(state(app), "finished", "split does nothing after the finish")
  mock.hotkey("reset")
  t.eq(state(app), "idle")
  t.eq(H.text(mock, "hud", "time"), "0:00.00")
end)

