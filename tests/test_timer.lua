local t = require("t")
local timer = require("timer")
local fmt = require("fmt")

t.case("game time from frames, real time from the clock", function()
  local tm = timer.new()
  tm:start(100, 5000)
  tm:update(160, 6500) -- 60 frames, 1500 ms
  t.eq(tm:game_ms(60), 1000)
  t.eq(tm:real_ms(), 1500)
  t.eq(tm:ms("game", 60), 1000)
  t.eq(tm:ms("real", 60), 1500)
  t.eq(tm:game_ms(59.83), math.floor(60 * 1000 / 59.83 + 0.5))
end)

t.case("game time stops while the frame stops, real time keeps going", function()
  local tm = timer.new()
  tm:start(0, 0)
  tm:update(60, 1000)
  tm:update(60, 3000) -- game paused for 2 s
  tm:update(90, 3500)
  t.eq(tm:game_ms(60), 1500)
  t.eq(tm:real_ms(), 3500)
end)

t.case("a frame counter that goes back counts nothing", function()
  local tm = timer.new()
  tm:start(1000, 0)
  tm:update(1060, 1000)
  tm:update(10, 1100) -- reset or loaded state
  tm:update(40, 1600)
  t.eq(tm:game_ms(60), 1000 + 500) -- 60 frames, then 30 frames after the new reference
end)

t.case("manual pause stops both clocks, resume continues", function()
  local tm = timer.new()
  tm:start(0, 0)
  t.ok(tm:pause(60, 1000))
  tm:update(300, 9000)
  t.eq(tm.state, "paused")
  t.eq(tm:game_ms(60), 1000)
  t.eq(tm:real_ms(), 1000)
  t.ok(tm:resume(300, 9000))
  tm:update(330, 9500)
  t.eq(tm:game_ms(60), 1500)
  t.eq(tm:real_ms(), 1500)
  t.ok(not tm:resume(0, 0), "resume only from paused")
end)

t.case("stop freezes, continue skips the gap", function()
  local tm = timer.new()
  tm:start(0, 0)
  t.ok(tm:stop(120, 2000))
  tm:update(500, 9000)
  t.eq(tm:game_ms(60), 2000)
  t.ok(tm:continue(500, 9000))
  tm:update(560, 9500)
  t.eq(tm:game_ms(60), 3000)
  t.eq(tm:real_ms(), 2500)
end)

t.case("start without a snapshot frame yet", function()
  local tm = timer.new()
  tm:start(nil, 0)
  tm:update(50, 100)
  tm:update(110, 200)
  t.eq(tm:game_ms(60), 1000) -- counts from the first frame it saw
end)

t.case("time formatting", function()
  t.eq(fmt.time(nil), "-")
  t.eq(fmt.time(0), "0:00.00")
  t.eq(fmt.time(61230), "1:01.23")
  t.eq(fmt.time(3723450), "1:02:03.45")
  t.eq(fmt.time(-1500), "-0:01.50")
  t.eq(fmt.delta(1234), "+1.23")
  t.eq(fmt.delta(-80000), "-1:20.00")
  t.eq(fmt.delta(0), "+0.00")
  t.eq(fmt.delta(nil), "")
end)
